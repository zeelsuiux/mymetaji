<?php
/**
 * My Metaji - city page file sync
 *
 * Included at the very end of config.php, once $services and $cities exist.
 * It keeps the root folder in step with those two arrays by writing one small
 * .php file per service x city combination:
 *
 *   accounting-software-surat.php
 *   inventory-software-vadodara.php
 *   gst-software-coimbatore.php
 *   ... and so on for all 7 services in all 18 cities.
 *
 * Each of those files is a 4-line stub that hands straight off to city-page.php,
 * so no page content is ever duplicated - there is only this file list to keep
 * in step. To publish a city, add it on the Master Panel (admin/master/cities.php)
 * and save: the next page load writes its files. To retire a city, delete it
 * there and its files are pruned.
 *
 * Cost on a normal request is one small file read. The expected file list is
 * hashed and compared against .city-pages.hash, so the create/prune work only
 * runs when $services or $cities has actually changed.
 *
 * Returns a small report so the Master Panel can tell the admin what went live:
 *   ['ran' => bool, 'created' => int, 'pruned' => int, 'writable' => bool]
 *
 * If either list comes back empty the sync does nothing at all. That is not a
 * normal state - it means config.php was loaded somewhere the two variables
 * cannot be seen (inside a function, say) - and pruning on it would delete
 * every city page on the site.
 *
 * If the folder is not writable the sync fails silently and the existing
 * pages keep working; nothing here is required for a page to render.
 */

function seo_sync_city_pages(): array
{
    global $services, $cities;

    $root = __DIR__ . '/..';

    if (empty($services) || empty($cities)) {
        error_log('[mymetaji] city pages sync skipped: $services or $cities is empty');
        return ['ran' => false, 'created' => 0, 'pruned' => 0, 'writable' => is_writable($root)];
    }

    // What the root folder should contain, and what goes inside each stub.
    $expected = [];
    foreach ($services as $service) {
        foreach ($cities as $city) {
            $expected[$service['slug'] . '-' . $city['slug'] . '.php'] = [$service['slug'], $city['slug']];
        }
    }

    $stampFile = $root . '/.city-pages.hash';
    $stamp     = md5(implode('|', array_keys($expected)));
    $cached    = is_readable($stampFile) ? trim((string) @file_get_contents($stampFile)) : '';

    if ($cached === $stamp) {
        return ['ran' => false, 'created' => 0, 'pruned' => 0, 'writable' => is_writable($root)];
    }

    $stub = "<?php\n"
          . "/**\n"
          . " * Auto-generated city page. Do not edit this file - it is rewritten\n"
          . " * from \$services and \$cities in config.php. Edit those instead.\n"
          . " */\n"
          . "\$service_slug = '%s';\n"
          . "\$city_slug    = '%s';\n"
          . "require __DIR__ . '/city-page.php';\n";

    $created = 0;
    foreach ($expected as $file => $pair) {
        $path = $root . '/' . $file;
        if (is_file($path)) {
            continue;
        }
        if (@file_put_contents($path, sprintf($stub, $pair[0], $pair[1])) !== false) {
            $created++;
        }
    }

    // Prune stubs this script wrote earlier that are no longer expected, i.e.
    // the city was removed from config.php. Only files carrying our own
    // generated header are ever deleted, so a hand-written page that happens to
    // share the naming pattern is left alone.
    $pruned = 0;
    foreach ((array) glob($root . '/*-software-*.php') as $path) {
        $file = basename($path);
        if (isset($expected[$file])) {
            continue;
        }
        $head = (string) @file_get_contents($path, false, null, 0, 120);
        if (strpos($head, 'Auto-generated city page') !== false && @unlink($path)) {
            $pruned++;
        }
    }

    @file_put_contents($stampFile, $stamp);

    if ($created || $pruned) {
        error_log('[mymetaji] city pages synced: ' . $created . ' created, ' . $pruned . ' pruned');
    }

    return ['ran' => true, 'created' => $created, 'pruned' => $pruned, 'writable' => is_writable($root)];
}

seo_sync_city_pages();
